"""规则分类器 v2：只分几个大类，宁少勿滥，优先保证正确率。

四个大类：技能学习 / 影视解说 / 生活消费 / 情绪共鸣，判不出归「未分类」。

做法上的取舍（针对 v1 噪声大的问题）：
1. 类目从七类砍到四类——类目越细，规则越容易互相抢词。
2. 词典只留「一看就属于这一类」的强特征词，剔掉「推荐、攻略、日常、人生、
   工作、如何、怎么」这种哪个类目都能沾的通用词。
3. 优先级：特征最独特的排前面（影视解说 → 情绪共鸣 → 生活消费 → 技能学习），
   命中并列时归更窄的类目。
4. 标题里天然带话题标签，短简介几乎全是 `#标签`，所以词典尽量用标签里
   真实会出现的词，而不是口语词。
"""
RULES = [
    ("影视解说", [
        "电影", "影视", "剧集", "美剧", "短剧", "纪录片", "影评",
        "大结局", "主演", "悬疑", "剧情", "韩剧", "烧脑",
    ]),
    ("情绪共鸣", [
        "情感", "共鸣", "情绪", "心理", "恋爱", "分手", "婚姻", "内耗",
        "扎心", "语录", "树洞", "emo", "焦虑", "孤独",
    ]),
    ("生活消费", [
        "美食", "菜谱", "做饭", "探店", "旅游", "旅行", "攻略", "酒店",
        "民宿", "好物", "测评", "开箱", "购物", "数码", "餐厅", "咖啡",
        "穿搭", "发型", "护肤",
    ]),
    ("技能学习", [
        "教程", "教学", "课程", "干货", "方法论", "技巧", "学会", "训练",
        "健身", "减脂", "增肌", "体态", "化妆", "声乐", "唱歌", "发声",
        "发音", "求职", "面试", "简历", "职场", "考研", "考公", "编程",
        "代码", "python", "工作流", "ai工具", "ai工作流", "ai绘画",
        "ai剪辑", "ai教程", "ai编程", "记忆法", "思维导图",
    ]),
]

UNCLASSIFIED = "未分类"


def classify(desc="", author=""):
    """返回 (类目, 命中数)。0 命中归「未分类」。"""
    text = f"{desc or ''} {author or ''}".lower()
    best, best_score = UNCLASSIFIED, 0
    for cat, kws in RULES:
        score = sum(1 for kw in kws if kw.lower() in text)
        if score > best_score:
            best, best_score = cat, score
    return best, best_score


def categories():
    return [c for c, _ in RULES] + [UNCLASSIFIED]
